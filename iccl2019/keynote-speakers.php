                <h2 class="iccl-color">Miguel Jaller Martelo</h2>
                <p><strong>Title: </strong> Changes in the Retail and Distribution Landscape: Behavioral and Logistics Modeling Implications </p>
                <p><strong>Description: </strong> In recent years, the rapid adoption of omni-channel distribution strategies has dramatically changed how we shop and the way companies design their retail and distribution operations. All these changes have important implications for logistics modeling from the strategic, tactical and operational perspectives. This presentation discusses the implications for assessing the shopping demand and logistics decisions under this dynamic environment. Specifically, Dr. Jaller will discuss changes in shopping decisions, from where to shop, what to shop, and how much to shop. The presentation will also provide an overview of the impacts of and tradeoffs between facility location, fleet and technology characteristics, time-windows, and the use of crowd-shipping services. Moreover, Dr. Jaller will cover the impacts from these decisions when thinking about the sustainability of the urban transportation system with respect to travel activity and emissions. </p>
