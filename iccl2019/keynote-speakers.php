                <h2 class="iccl-color">Jose Holguin-Veras</h2>
                <p><strong>Title: </strong> The Quest for Sustainable Urban Logistics in an Era of Rapid (and Unpredictable) Technological and Economic Change </p>
                <p><strong>Description: </strong> In this talk, Professor Holguín-Veras will discuss the challenges and opportunities presented by the rise of the internet and on-demand economy, and the development of novel vehicular technologies. These trends--from both the demand and supply sides--have led to significant increases in the number of freight deliveries and shipments made in urban areas; and to increase congestion, emissions, and conflicts with pedestrian and cyclists. The reactions to these effects on the part of various stakeholders have been mixed. Individuals seem to enjoy the new services provided. Users of transportation networks complain about the increasing freight traffic. Municipalities have, for the most part, decided not to interfere with these deployments. Freight carriers are both concerned by the challenges presented to them, and excited by the opportunities. In this talk, Professor Holguín-Veras will share his thoughts about how to make the most of these challenges and opportunities. </p>
