                <h2 class="iccl-color">Benjamín Hazen</h2>
                <p><strong>Title: </strong> Supply Chain Management at the International-Level:  How Computational Logistics Scholars Might Contribute </p>
                <p><strong>Description: </strong> Supply chain management activities are conducted in and serve nearly every region of the globe. The interdependences created via these ubiquitous and increasingly global trade relationships command the need for more attention on the international-level of supply chain management. However, most supply chain research is conducted at the organizational-level, with very few studies considering a supply chain-level of analysis. To date, the body of knowledge on national and international perspectives of global trade is found in policy, strategy, government, international relations, defense, and other journals and magazines primarily grounded in the social sciences. This talk will describe some of these international-level supply chain management issues. It will also discuss needs and opportunities for transdisciplinary collaboration seeking to solve international-level SCM problems like sustainability. </p>
